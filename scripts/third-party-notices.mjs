#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md: every Rust crate compiled into the
// shipped binaries (desktop app and native messaging host, no dev or test
// dependencies), every npm package bundled into the user interface, and the
// bundled tools, each with its license text.
//
// Usage: node scripts/third-party-notices.mjs

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "THIRD_PARTY_NOTICES.md");
const ROOTS = ["velox-desktop", "velox-nm"];
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

function licenseTexts(dir) {
  let names;
  try {
    names = fs.readdirSync(dir);
  } catch {
    return [];
  }
  return names
    .filter((n) => LICENSE_FILE.test(n) && fs.statSync(path.join(dir, n)).isFile())
    .sort()
    .map((n) => fs.readFileSync(path.join(dir, n), "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean);
}

// ----- Rust -------------------------------------------------------------------
const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: root, encoding: "utf8", maxBuffer: 256 << 20 }),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const workspace = new Set(meta.workspace_members);
const seen = new Set();
const stack = meta.packages.filter((p) => ROOTS.includes(p.name) && workspace.has(p.id)).map((p) => p.id);
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    // Normal and build dependencies end up in (or produce) the binaries.
    if (d.dep_kinds.some((k) => k.kind === null || k.kind === "build")) stack.push(d.pkg);
  }
}
const crates = [...seen]
  .filter((id) => !workspace.has(id))
  .map((id) => pkgs.get(id))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// ----- npm ----------------------------------------------------------------------
let npm = [];
try {
  const raw = execFileSync("pnpm", ["--filter", "desktop", "licenses", "list", "--prod", "--json"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 << 20,
    shell: process.platform === "win32",
  });
  for (const [license, list] of Object.entries(JSON.parse(raw))) {
    for (const p of list) {
      for (const v of p.versions ?? [p.version]) npm.push({ name: p.name, version: v, license, dir: (p.paths ?? [])[0], homepage: p.homepage });
    }
  }
} catch (e) {
  console.error(`warning: npm licenses unavailable: ${e.message}`);
}
npm.sort((a, b) => a.name.localeCompare(b.name));

// ----- bundled tools -------------------------------------------------------------
const lock = JSON.parse(fs.readFileSync(path.join(root, "resources", "sidecars.lock.json"), "utf8"));

// ----- output --------------------------------------------------------------------
const texts = new Map(); // text -> index
const textId = (t) => {
  if (!texts.has(t)) texts.set(t, texts.size + 1);
  return texts.get(t);
};
const lines = [
  "# Third-party notices",
  "",
  "Velox Download Manager is distributed under the MIT or Apache-2.0 license. It",
  "includes the third-party software listed below, each under its own license.",
  "This file is generated by `scripts/third-party-notices.mjs`.",
  "",
  "## Bundled programs",
  "",
  "| Program | Version | License | Source |",
  "|---|---|---|---|",
];
for (const [name, t] of Object.entries(lock.tools)) lines.push(`| ${name} | ${t.version} | ${t.license} | ${t.source} |`);
lines.push(
  "",
  "FFmpeg is a separate program run by Velox; it is not linked into Velox. The",
  "bundled builds are LGPL builds from https://github.com/BtbN/FFmpeg-Builds",
  "(build scripts and FFmpeg source are published there and at",
  "https://ffmpeg.org/download.html). yt-dlp is released into the public domain",
  "(Unlicense). On Windows, the installer may install the Microsoft Edge WebView2",
  "Runtime, which is licensed by Microsoft under its own terms.",
  "",
  `## Rust crates (${crates.length})`,
  "",
  "| Crate | Version | License | Text |",
  "|---|---|---|---|",
);
for (const c of crates) {
  const ids = licenseTexts(path.dirname(c.manifest_path)).map(textId);
  lines.push(`| ${c.name} | ${c.version} | ${c.license ?? c.license_file ?? "see text"} | ${ids.map((i) => `[${i}](#license-${i})`).join(" ") || "-"} |`);
}
lines.push("", `## npm packages in the user interface (${npm.length})`, "", "| Package | Version | License | Text |", "|---|---|---|---|");
for (const p of npm) {
  const ids = p.dir ? licenseTexts(p.dir).map(textId) : [];
  lines.push(`| ${p.name} | ${p.version} | ${p.license} | ${ids.map((i) => `[${i}](#license-${i})`).join(" ") || "-"} |`);
}
lines.push("", "## License texts", "");
for (const [text, id] of texts) {
  lines.push(`<a id="license-${id}"></a>`, `### ${id}`, "", "```text", text.replace(/```/g, "'''"), "```", "");
}
fs.writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`${path.relative(root, out)}: ${crates.length} crates, ${npm.length} npm packages, ${texts.size} distinct license texts`);
